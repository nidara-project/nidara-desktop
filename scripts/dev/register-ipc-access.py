"""install.sh's explicit dev grants. This program is not run by the desktop.

--print emits the reviewable configuration without privilege or any system write.
The writer always targets /etc/nidara/access.d; no environment-based destination.
"""
import argparse
import os
from pathlib import Path
import secrets
import stat

DIRECTORY = '/etc/nidara/access.d'

def grants(repo, uid):
    repo = Path(repo).resolve(strict=True)
    paths = [
        ('legacy-shell', 'lib/nidara-host/build/nidara-shell'),
        ('legacy-settings', 'lib/nidara-host/build/nidara-settings'),
        ('settings', 'toolkit/target/release/nk-settings'),
        ('session', 'session/target/release/nidara-sessiond'),
    ]
    lines = ['# Generated by install.sh --dev. Exact executable grants for this UID.']
    for role, relative in paths:
        path = str((repo / relative).resolve())
        if any(c in path for c in '\t\n\r\x00'):
            raise ValueError('development executable path contains a control character')
        lines.append(f'{role}\t{uid}\t{path}')
    return '\n'.join(lines) + '\n'

def secure_directory():
    fd = os.open('/', os.O_RDONLY | os.O_DIRECTORY | os.O_CLOEXEC)
    try:
        initial = os.fstat(fd)
        if initial.st_uid != 0 or initial.st_mode & 0o022:
            raise PermissionError('unsafe filesystem root')
        for part in DIRECTORY.split('/')[1:]:
            created = False
            try:
                os.mkdir(part, mode=0o755, dir_fd=fd)
                created = True
            except FileExistsError:
                pass
            child = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW | os.O_CLOEXEC, dir_fd=fd)
            os.close(fd)
            fd = child
            if created:
                os.fchmod(fd, 0o755)
            m = os.fstat(fd)
            if m.st_uid != 0 or m.st_mode & 0o022:
                raise PermissionError(f'{DIRECTORY}: root-owned directories without group/world write required')
        return fd
    except BaseException:
        os.close(fd)
        raise

def write(uid, text):
    if os.geteuid() != 0:
        raise PermissionError('writing developer IPC grants requires root (install.sh --dev)')
    directory = secure_directory()
    temporary = f'.dev-{uid}-{secrets.token_hex(8)}.tmp'
    target = f'dev-{uid}.conf'
    try:
        try:
            m = os.stat(target, dir_fd=directory, follow_symlinks=False)
        except FileNotFoundError:
            pass
        else:
            if not stat.S_ISREG(m.st_mode) or m.st_uid != 0 or stat.S_IMODE(m.st_mode) != 0o644:
                raise PermissionError(f'{target}: refusing to replace unsafe existing configuration')
        fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC, 0o600, dir_fd=directory)
        with os.fdopen(fd, 'w') as stream:
            stream.write(text)
            stream.flush()
            os.fchmod(stream.fileno(), 0o644)
            os.fsync(stream.fileno())
        os.replace(temporary, target, src_dir_fd=directory, dst_dir_fd=directory)
        os.fsync(directory)
    finally:
        try:
            os.unlink(temporary, dir_fd=directory)
        except FileNotFoundError:
            pass
        os.close(directory)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', required=True)
    parser.add_argument('--uid', required=True, type=int)
    parser.add_argument('--print', action='store_true', dest='print_only')
    args = parser.parse_args()
    if not 0 <= args.uid <= 2**32 - 1:
        parser.error('UID outside uint32 range')
    text = grants(args.repo, args.uid)
    if args.print_only:
        print(text, end='')
    else:
        write(args.uid, text)

if __name__ == '__main__':
    main()
